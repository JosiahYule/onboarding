export function BrandMark({ size = 28, tone = 'brand' }) {
  // Several marks can share a page and two elements may not share an id, so
  // each instance carries its own gradient.
  const gradientId = `isl-gear-${useId().replace(/[^a-zA-Z0-9]/g, '')}`
  return (
    <svg className="brand__mark" width={size} height={size} viewBox="0 0 64 64" fill="none" aria-hidden="true" style={{ flex: 'none' }}>
      {tone === 'brand' && (
        <defs>
          <linearGradient id={gradientId} x1="8" y1="6" x2="56" y2="58" gradientUnits="userSpaceOnUse">
            <stop stopColor="var(--brand-strong)" />
            <stop offset="1" stopColor="var(--brand)" />
          </linearGradient>
        </defs>
      )}
      <path d={GEAR} fill={tone === 'inverse' ? '#ffffff' : `url(#${gradientId})`} />
    </svg>
  )
}

